package com.vyonex.internal.fallback.services.peertube

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.booleanOrNull

internal data class PeertubeCaption(
    val language: String,
    val path: String,
    val autoGenerated: Boolean,
)

internal object PeertubeCaptionResponseParser {
    fun parse(source: String): List<PeertubeCaption> {
        val response = Json.parseToJsonElement(source) as? JsonObject
            ?: throw IllegalArgumentException("Caption response must be a JSON object")
        return response.array("data").mapNotNull(::caption)
    }

    private fun caption(value: JsonElement): PeertubeCaption? {
        val caption = value as? JsonObject ?: return null
        val language = (caption["language"] as? JsonObject)?.string("id")
            ?.takeIf(String::isNotBlank) ?: return null
        val path = caption.string("fileUrl")?.takeIf(String::isNotBlank)
            ?: caption.string("captionPath")?.takeIf(String::isNotBlank)
            ?: caption.string("m3u8Url")?.takeIf(String::isNotBlank)
            ?: return null
        return PeertubeCaption(language, path, caption.boolean("automaticallyGenerated"))
    }

    private fun JsonObject.array(name: String): JsonArray =
        this[name] as? JsonArray ?: JsonArray(emptyList())

    private fun JsonObject.string(name: String): String? =
        (this[name] as? JsonPrimitive)?.takeIf { it.isString }?.content

    private fun JsonObject.boolean(name: String): Boolean =
        (this[name] as? JsonPrimitive)?.takeUnless { it.isString }?.booleanOrNull ?: false
}
