package com.vyonex.internal.fallback.services.youtube.extractors;

import com.vyonex.internal.fallback.MediaFormat;
import com.vyonex.internal.json.JsonParser;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

class YoutubeStreamSubtitleTest {
    @Test
    void removesOldFormatAndTranslationBeforeAddingRequestedFormat() throws Exception {
        final var tracks = JsonParser.object().from("{\"captionTracks\":[{"
                + "\"languageCode\":\"en\",\"baseUrl\":\"https://captions.example/api?"
                + "v=video&fmt=srv3&tlang=de\",\"vssId\":\"a.en\"},{"
                + "\"languageCode\":\"fr\",\"baseUrl\":\"https://captions.example/fr\"}]}");

        final var subtitles = YoutubeStreamExtractor.parseSubtitles(tracks, MediaFormat.TTML);

        assertEquals(1, subtitles.size());
        assertEquals("https://captions.example/api?v=video&fmt=ttml",
                subtitles.get(0).getContent());
        assertEquals("en", subtitles.get(0).getLanguageTag());
        assertTrue(subtitles.get(0).isAutoGenerated());
    }
}
