package com.vyonex.internal.fallback.services.youtube.extractors;

import com.vyonex.internal.fallback.ListExtractor;
import com.vyonex.internal.fallback.exceptions.ParsingException;
import com.vyonex.internal.json.JsonParser;
import org.junit.jupiter.api.Test;

import static com.vyonex.internal.fallback.services.youtube.linkHandler.YoutubeSearchQueryHandlerFactory.MUSIC_ALBUMS;
import static com.vyonex.internal.fallback.services.youtube.linkHandler.YoutubeSearchQueryHandlerFactory.MUSIC_PLAYLISTS;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;

class YoutubeMusicAlbumOrPlaylistInfoItemExtractorContractTest {
    @Test
    void mapsAlbumMetadataAndUsesMenuRoutes() throws Exception {
        final var item = JsonParser.object().from("""
                {
                  "flexColumns":[{"musicResponsiveListItemFlexColumnRenderer":{"text":{"simpleText":"Album"}}}],
                  "thumbnail":{"musicThumbnailRenderer":{"thumbnail":{"thumbnails":[
                    {"url":"//img.example/album.jpg","width":320,"height":320}
                  ]}}},
                  "menu":{"menuRenderer":{"items":[
                    {"toggleMenuServiceItemRenderer":{"toggledServiceEndpoint":{"likeEndpoint":{"target":{"playlistId":"OLAK5"}}}}},
                    {"menuNavigationItemRenderer":{"icon":{"iconType":"ARTIST"},"navigationEndpoint":{"browseEndpoint":{"browseId":"UC789"}}}}
                  ]}}
                }
                """);
        final var descriptions = JsonParser.array().from("""
                [{"text":"Album"},{"text":" • "},{"text":"Creator","navigationEndpoint":{"browseEndpoint":{"browseId":"UC789"}}}]
                """);
        final var extractor = new YoutubeMusicAlbumOrPlaylistInfoItemExtractor(
                item, descriptions, MUSIC_ALBUMS);

        assertEquals("Album", extractor.getName());
        assertEquals("https://music.youtube.com/playlist?list=OLAK5", extractor.getUrl());
        assertEquals("https://img.example/album.jpg", extractor.getThumbnails().get(0).getUrl());
        assertEquals("Creator", extractor.getUploaderName());
        assertEquals("https://www.youtube.com/channel/UC789", extractor.getUploaderUrl());
        assertFalse(extractor.isUploaderVerified());
        assertEquals(ListExtractor.ITEM_COUNT_UNKNOWN, extractor.getStreamCount());
    }

    @Test
    void usesPlayOverlayRouteAndHandlesAutogeneratedUploader() throws Exception {
        final var item = JsonParser.object().from("""
                {
                  "flexColumns":[{"musicResponsiveListItemFlexColumnRenderer":{"text":{"simpleText":"Playlist"}}}],
                  "overlay":{"musicItemThumbnailOverlayRenderer":{"content":{"musicPlayButtonRenderer":{"playNavigationEndpoint":{"watchPlaylistEndpoint":{"playlistId":"PL456"}}}}}}
                }
                """);
        final var extractor = new YoutubeMusicAlbumOrPlaylistInfoItemExtractor(item,
                JsonParser.array().from("[{\"text\":\"Auto-generated\"}]"), MUSIC_PLAYLISTS);

        assertEquals("https://music.youtube.com/playlist?list=PL456", extractor.getUrl());
        assertEquals("Auto-generated", extractor.getUploaderName());
        assertNull(extractor.getUploaderUrl());
        assertThrows(ParsingException.class,
                () -> new YoutubeMusicAlbumOrPlaylistInfoItemExtractor(item,
                        JsonParser.array().from("[]"), MUSIC_PLAYLISTS).getUploaderName());
    }
}
