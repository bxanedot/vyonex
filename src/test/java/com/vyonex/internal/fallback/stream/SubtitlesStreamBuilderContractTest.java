package com.vyonex.internal.fallback.stream;

import com.vyonex.internal.fallback.MediaFormat;
import com.vyonex.internal.fallback.exceptions.ParsingException;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

class SubtitlesStreamBuilderContractTest {
    @Test
    void buildsSubtitleStreamWithDerivedIdAndMetadata() throws Exception {
        final SubtitlesStream stream = new SubtitlesStream.Builder()
                .setContent("caption data", false)
                .setLanguageCode("en-US")
                .setMediaFormat(MediaFormat.VTT)
                .setDeliveryMethod(DeliveryMethod.PROGRESSIVE_HTTP)
                .setAutoGenerated(true)
                .setManifestUrl("https://media.example/manifest")
                .build();

        assertEquals("en-US.vtt", stream.getId());
        assertEquals("caption data", stream.getContent());
        assertFalse(stream.isUrl());
        assertEquals("vtt", stream.getExtension());
        assertEquals("en-US", stream.getLanguageTag());
        assertTrue(stream.isAutoGenerated());
        assertEquals("https://media.example/manifest", stream.getManifestUrl());
        assertNull(stream.getItagItem());
    }

    @Test
    void rejectsBuildsMissingRequiredFieldsAndMalformedLanguage() {
        assertThrows(IllegalStateException.class, () -> new SubtitlesStream.Builder().build());
        assertThrows(ParsingException.class, () -> new SubtitlesStream.Builder()
                .setContent("data", false)
                .setLanguageCode("")
                .setAutoGenerated(false)
                .build());
    }
}
