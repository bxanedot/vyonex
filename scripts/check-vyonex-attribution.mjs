import {existsSync, readFileSync, readdirSync} from "node:fs";
import {dirname, join, relative, resolve, sep} from "node:path";
import {fileURLToPath} from "node:url";

const repositoryRoot=resolve(dirname(fileURLToPath(import.meta.url)),"..");
const root=resolve(process.argv[2]??repositoryRoot);
const roots=["src","ci","scripts"];
const ownedFiles=new Set([
 "src/commonMain/kotlin/com/vyonex/BandcampClient.kt",
 "src/commonMain/kotlin/com/vyonex/BandcampTrack.kt",
 "src/commonTest/kotlin/com/vyonex/BandcampClientTest.kt"
]);
const extensions=new Set([".kt",".kts",".java",".swift",".m",".mm",".h",".hpp",".c",".cc",".cpp",".js",".mjs",".cjs",".ts",".tsx",".jsx",".py",".sh",".bash",".go",".rs",".css",".html",".xml",".sql",".cmake",".ps1",".bat"]);
const ignored=new Set([".git","node_modules","build","generated","out","vendor","third_party"]);

function filesIn(directory){
 if(!existsSync(directory))return [];
 return readdirSync(directory,{withFileTypes:true}).flatMap(entry=>{
  const path=join(directory,entry.name);
  if(entry.isDirectory())return ignored.has(entry.name)?[]:filesIn(path);
  if(!entry.isFile()||!extensions.has(entry.name.slice(entry.name.lastIndexOf(".")).toLowerCase()))return [];
  const text=readFileSync(path,"utf8");
  if(/Code generated .*DO NOT EDIT|Generated by .*Do not edit/i.test(text.split(/\r?\n/).slice(0,8).join("\n")))return [];
  return [{path,relativePath:relative(root,path).split(sep).join("/")}];
 });
}

const files=roots.flatMap(name=>filesIn(join(root,name))).filter(({path})=>{
 return ownedFiles.has(relative(root,path).split(sep).join("/"));
});
const missing=files.filter(({path})=>{
 const header=readFileSync(path,"utf8").split(/\r?\n/).slice(0,12).join("\n");
 return !header.includes("bxane")||!header.includes("SPDX-FileCopyrightText: 2026 bxane");
});
if(missing.length){
 console.error(`VyonEx attribution missing from ${missing.length} of ${files.length} first-party source files:`);
 for(const file of missing)console.error(`- ${file.relativePath}`);
 process.exitCode=1;
}else console.log(`VyonEx attribution verified in all ${files.length} first-party source files.`);
