import assert from "node:assert/strict";
import {mkdtempSync, mkdirSync, rmSync, writeFileSync} from "node:fs";
import {tmpdir} from "node:os";
import {join, resolve} from "node:path";
import {fileURLToPath} from "node:url";
import {spawnSync} from "node:child_process";
import test from "node:test";

const root=mkdtempSync(join(tmpdir(),"vyonex-attribution-"));
const script=resolve(fileURLToPath(new URL("./check-vyonex-attribution.mjs",import.meta.url)));

test("checks source and excludes generated and vendored code",t=>{
 t.after(()=>rmSync(root,{recursive:true,force:true}));
 const source=join(root,"src/commonMain/kotlin/com/vyonex/BandcampClient.kt");
 const vendor=join(root,"src/commonMain/vendor/Vendor.kt");
 const generated=join(root,"src/commonMain/generated/Generated.kt");
 const owned=join(root,"src/commonMain/kotlin/com/vyonex/BandcampClient.kt");
 mkdirSync(join(root,"src/commonMain/vendor"),{recursive:true});
 mkdirSync(join(root,"src/commonMain/generated"),{recursive:true});
 mkdirSync(join(root,"src/commonMain/kotlin/com/vyonex"),{recursive:true});
 writeFileSync(source,"package example\n");
 writeFileSync(owned,"package example\n");
 writeFileSync(vendor,"class Vendor\n");
 writeFileSync(generated,"// Code generated by fixture. DO NOT EDIT.\nclass Generated\n");
 let result=spawnSync(process.execPath,[script,root],{encoding:"utf8"});
 assert.equal(result.status,1);
 assert.match(result.stderr,/BandcampClient\.kt/);
 assert.match(result.stderr,/BandcampClient\.kt/);
 assert.doesNotMatch(result.stderr,/Vendor\.kt|Generated\.kt/);
 writeFileSync(source,"// VyonEx — by bxane\n// SPDX-FileCopyrightText: 2026 bxane\npackage example\n");
 writeFileSync(owned,"// VyonEx — by bxane\n// SPDX-FileCopyrightText: 2026 bxane\npackage example\n");
 result=spawnSync(process.execPath,[script,root],{encoding:"utf8"});
 assert.equal(result.status,0,result.stderr||result.stdout);
});
